"""Generate `design.yaml` for logper-0800-6000 (phase A: coax feed, no case).

The bow-tie array is 15 elements per copper layer whose vertices all follow
one rule (element n is element 0 scaled by tau^n, alternating sides), so the
spec is generated rather than typed. `design.yaml` remains the artifact the
compiler builds; re-run this only to change the element COUNT or the rule.
Dimension changes are variable edits in `design.yaml` / the AEDT table.

    python workspaces/logper-0800-6000/tools/make_spec.py

Frame: +x along the board from the wide base (x=0) to the tip (x=pcb_L),
y transverse, z normal. Substrate occupies 0..h. The coax lies on the z=h
copper (KiCad F.Cu, CST "BOTTOM_RAD"); the far copper is at z=0 (KiCad B.Cu,
CST "TOP_RAD").
"""
from pathlib import Path

N = 15  # elements per layer: n even on one side, n odd on the other

HEADER = '''\
# logper-0800-6000 - printed log-periodic bow-tie dipole array, 0.8-6 GHz.
# Phase A: coax-fed, no enclosure. HFSS replica of the CST model
# "2_WITH_FEED_COAX_FR4_V1" in the ByTechLab repo
# (Repos/LogPer_Antenna/RF---PCB-Log-Periodic-Antenna--0.8-6-GHz-).
#
# GENERATED by tools/make_spec.py - the 30 bow-tie polylines follow one rule.
#
# Sources, cross-checked against each other in the Clarification block:
#   - CST parameter list (Touchstone header of
#     SIM_LOG_PERIODIC_COAX_FEED_WITHOUT_CASE.s1p)
#   - CST's own CAD export (CST_SIM/2_.../RESULTS/CAD/LOG_PERIOD.stp):
#     coax radii, coax axis height, wire bend, board outline
#   - KiCad copper polygons (LOG_PERIODIC_PCB.kicad_pcb, F.Cu / B.Cu)
#
# Frame: +x base -> tip, y transverse, z normal; substrate 0..h; coax on the
# z = h copper, far copper at z = 0.
#
# Element rule (n = 0..14): scale s_n = tau^n, centre xc_n = xc_(n-1) +
# bt_sp1*s_(n-1), root width bt_Wr1*s_n on the centreline, end width
# bt_We1*s_n at distance bt_L1*s_n. On the coax-side copper even n points +y;
# the far copper is the mirror image. Powers are written as chained products
# because the offline validator parses Python syntax and AEDT wants `^`.
#
# NOT expressible in schema v1, applied by post-compile staged scripts
# (recorded in state.md as Route-B add-ons):
#   src/20_feed_bend.py     - the centre conductor's 1.5 mm-radius bend
#   src/21_fr4_dispersion.py- FR-4 eps'(f), tand(f) from CST's fit tables
#   src/22_setup_extras.py  - broadband adaptive, field sweep, far-field sphere
spec_version: 1
name: logper-0800-6000
recipe: printed-log-periodic-bowtie-array
solution_type: Modal            # explicit, never the default (env-compat #11)

provenance:
  source: "ByTechLab PCB Log Periodic Antenna (0.8-6 GHz), CST model 2_WITH_FEED_COAX_FR4_V1; design basis Abdulhameed & Kubik, Electronics 2022, 11, 2877"
  canonical_reading: measured
  notes: >-
    As-built dimensions of the CST model are canonical, not the paper's
    equations: CST parameter list, CST STEP export and KiCad copper agree
    (feed 4 x 203.5 mm, element 0 = 60 mm / 30 mm / 5 mm, tau 0.85, coax
    0.255/0.76/1.045 mm, axis 1.03 mm above the copper, bend radius 1.5 mm).
    Substrate 1.5 mm as simulated in CST (KiCad stackup says 1.51 mm).
    Copper is zero-thickness finite-conductivity sheets here (CST: 35 um
    solids).

variables:
  f_lo: 0.8GHz
  f_hi: 6GHz
  h: 1.5mm                        # dielectric_thickness
  pcb_L: 205mm                    # pcb_length
  pcb_Wbase: 160mm                # pcb_width_base
  pcb_Wtip: 20mm                  # pcb_width_top
  feed_W: 4mm                     # feed_line_width
  feed_cut: 1.5mm                 # feed_cut_len: coax-side line stops short of the tip
  tau: 0.85                       # bowtie_linear_scaling_factor
  bt_L1: 60mm                     # first_bowtie_length, from the centreline
  bt_We1: 30mm                    # first_bowtie_width_end
  bt_Wr1: 5mm                     # first_bowtie_width, on the centreline
  bt_x1: 18mm                     # first_bowtie_start_offset
  bt_sp1: 30mm                    # first_bowtie_pos_offset
  r_in: 0.255mm                   # coax centre conductor radius
  r_d: 0.76mm                     # coax dielectric radius
  r_sh: 1.045mm                   # coax shield outer radius
  coax_zoff: 1.03mm               # coax axis above the copper plane (shield sinks 0.015 mm)
  bend_R: 1.5mm                   # cnd_off3: centre-conductor bend radius
  wire_tail: 0.25mm               # cnd_off1: wire protrudes below the far copper
  cap_L: 1mm                      # PEC cap backing the internal wave port
  coax_L: "pcb_L - feed_cut"
  zc: "h + coax_zoff"
  air_pad: "c0 / (4 * f_lo)"      # lambda/4 at the LOWEST frequency (93.7 mm)
'''

MATERIALS = '''
materials:
  # Placeholder constants (band-centre of CST's fit). src/21_fr4_dispersion.py
  # replaces them with eps'(f), tand(f) datasets taken from CST's exported
  # "FR-4 (lossy)" fit: 4.81 @ 0.8 GHz -> 4.65 @ 6 GHz, tand 0.023-0.025.
  fr4_cst:
    permittivity: 4.72
    loss_tangent: 0.024
  # CST "PTFE (lossy)" as fitted in the model: 1.70, which with these radii
  # gives a 50.3 ohm line. Not the textbook 2.1.
  ptfe_coax:
    permittivity: 1.70
    loss_tangent: 0.0002
  # CST "Copper (pure)". Used on the 3D coax conductors only; the board
  # copper is a finite-conductivity boundary on sheets (env-compat #17).
  cu_pure:
    permittivity: 1.0
    conductivity: 59600000
  cap_pec:
    library: pec
  air:
    library: air
'''


def lines_for_layer(prefix: str, z: str, even_sign: int, feed_len: str) -> list[str]:
    out = [
        f"  - op: sheet",
        f"    name: {prefix}Cu",
        f"    plane: xy",
        f'    origin: ["0mm", "-feed_W/2", {z}]',
        f'    size: [{feed_len}, feed_W]',
    ]
    names = []
    for n in range(N):
        sign = even_sign if n % 2 == 0 else -even_sign
        name = f"{prefix}BT{n:02d}"
        names.append(name)
        xl_r = f"xc{n} - bt_Wr1*s{n}/2"
        xr_r = f"xc{n} + bt_Wr1*s{n}/2"
        xl_e = f"xc{n} - bt_We1*s{n}/2"
        xr_e = f"xc{n} + bt_We1*s{n}/2"
        if sign > 0:   # counter-clockwise seen from +z
            pts = [(xl_r, "0mm"), (xr_r, "0mm"),
                   (xr_e, f"bt_L1*s{n}"), (xl_e, f"bt_L1*s{n}")]
        else:
            pts = [(xl_r, "0mm"), (xl_e, f"-bt_L1*s{n}"),
                   (xr_e, f"-bt_L1*s{n}"), (xr_r, "0mm")]
        out += [f"  - op: polyline", f"    name: {name}",
                f"    cover: true", f"    close: true", f"    points:"]
        out += [f'      - ["{x}", "{y}", {z}]' for x, y in pts]
    out += [f"  - op: unite", f"    name: {prefix}Cu",
            f"    with: [{', '.join(names)}]"]
    return out


def main() -> None:
    text = [HEADER.rstrip("\n")]
    text.append("  s0: 1")
    for n in range(1, N):
        text.append(f'  s{n}: "s{n-1} * tau"')
    text.append("  xc0: bt_x1")
    for n in range(1, N):
        text.append(f'  xc{n}: "xc{n-1} + bt_sp1 * s{n-1}"')
    text.append(MATERIALS.rstrip("\n"))
    g = ["", "geometry:",
         "  # Trapezoidal board, as CST's PCB solid (no mounting holes in the CST model).",
         "  - op: polyline", "    name: Substrate", "    material: fr4_cst",
         "    cover: true", "    close: true", "    points:",
         '      - ["0mm", "-pcb_Wbase/2", "0mm"]',
         '      - [pcb_L, "-pcb_Wtip/2", "0mm"]',
         '      - [pcb_L, "pcb_Wtip/2", "0mm"]',
         '      - ["0mm", "pcb_Wbase/2", "0mm"]',
         "  - op: thicken_sheet", "    name: Substrate", "    thickness: h",
         "",
         "  # Coax-side copper (KiCad F.Cu): feed line stops feed_cut short of the tip.",
         "  # No material: sheets become metal by the boundaries below."]
    g += lines_for_layer("Top", "h", +1, "coax_L")
    g += ["",
          "  # Far-side copper (KiCad B.Cu): mirror image, feed line runs to the tip."]
    g += lines_for_layer("Bot", '"0mm"', -1, "pcb_L")
    g += ['''
  # --- coax, lying on the coax-side feed line, base (x=0) to coax_L ---------
  # Order matters for idempotency: CoaxDiel keeps InnerCond as a cloned tool,
  # so on a re-run the stale CoaxDiel must be deleted (by its own op) BEFORE
  # InnerCond is recreated, or AEDT renames the new one InnerCond_2.
  - op: cylinder
    name: CoaxDiel
    material: ptfe_coax
    axis: x
    origin: ["0mm", "0mm", zc]
    radius: r_d
    height: coax_L
  - op: cylinder
    name: InnerCond
    material: cu_pure
    axis: x
    origin: ["0mm", "0mm", zc]
    radius: r_in
    height: coax_L
  - op: subtract
    name: CoaxDiel
    tools: [InnerCond]
    keep_tools: true
  - op: cylinder
    name: Shield
    material: cu_pure
    axis: x
    origin: ["0mm", "0mm", zc]
    radius: r_sh
    height: coax_L
  - op: cylinder
    name: ShieldBore
    axis: x
    origin: ["0mm", "0mm", zc]
    radius: r_d
    height: coax_L
  # CST sinks the shield 0.015 mm into its 35 um trace. With sheet copper the
  # same overlap would cut into the substrate, so the shield is trimmed flat at
  # z = h: it rests on the trace through a 0.35 mm wide facet, as in CST.
  - op: box
    name: ShieldTrim
    origin: ["-1mm", "-r_sh", "h - 1mm"]
    size: ["coax_L + 2mm", "2*r_sh", "1mm"]
  - op: subtract
    name: Shield
    tools: [ShieldBore, ShieldTrim]
    keep_tools: false

  # Centre conductor's vertical leg on the board tip edge (x = pcb_L): from
  # wire_tail below the far copper up to the start of the bend. The bend that
  # joins it to InnerCond is src/20_feed_bend.py (no circle primitive / swept
  # arc in schema v1).
  - op: cylinder
    name: WireLeg
    material: cu_pure
    axis: z
    origin: [pcb_L, "0mm", "-wire_tail"]
    radius: r_in
    height: "wire_tail + zc - bend_R"
  # The wire is half-buried in the board edge and passes through the far
  # copper: notch both, as CST's PCB and copper solids are notched.
  - op: subtract
    name: Substrate
    tools: [WireLeg]
    keep_tools: true
  - op: subtract
    name: BotCu
    tools: [WireLeg]
    keep_tools: true

  # PEC cap behind the coax end: backs the internal wave port (a wave port
  # must sit on an outer boundary or a conductor - Global/Ports notes).
  - op: cylinder
    name: PortCap
    material: cap_pec
    axis: x
    origin: ["-cap_L", "0mm", zc]
    radius: r_sh
    height: cap_L

  # Radiation box: lambda/4 at f_lo on every side.
  - op: box
    name: AirBox
    material: air
    origin: ["-air_pad - cap_L", "-pcb_Wbase/2 - air_pad", "-air_pad"]
    size: ["pcb_L + cap_L + 2*air_pad", "pcb_Wbase + 2*air_pad", "h + 2*r_sh + 2*air_pad"]

excitations:
  # Coax TEM mode on the dielectric's annular end face at x = 0 (CST: 50 ohm
  # discrete port at the same coax end). Line Z0 = 50.3 ohm, renormalised to 50.
  - name: P1
    type: wave_port
    on:
      face_of: CoaxDiel
      direction: "-x"
    impedance: 50ohm
    renormalize: true

boundaries:
  - name: TopCuMetal
    type: finite_conductivity
    on:
      object: TopCu
    conductivity: 59600000
  - name: BotCuMetal
    type: finite_conductivity
    on:
      object: BotCu
    conductivity: 59600000
  - name: Rad1
    type: radiation
    on:
      outer_faces: AirBox

mesh:
  - type: adaptive_only

# Baseline setup; src/22_setup_extras.py switches the adaptive solve to
# broadband (f_lo..f_hi) and adds the field sweep + far-field sphere.
setup:
  name: Setup1
  solution_frequency: f_hi
  max_passes: 12
  delta_s: 0.02
  sweep:
    name: Sweep1
    type: interpolating
    start: 0.4GHz
    stop: 6.5GHz
    count: 611

qa_signals: [convergence, ports_excited, in_band_resonance, energy_pass]
''']
    text += g
    target = Path(__file__).resolve().parent.parent / "design.yaml"
    target.write_text("\n".join(text), encoding="utf-8", newline="\n")
    print(f"wrote {target}")


if __name__ == "__main__":
    main()
